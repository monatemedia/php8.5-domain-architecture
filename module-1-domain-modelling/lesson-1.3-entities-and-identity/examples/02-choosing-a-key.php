// ═══════════════════════════════════════════════════════════════════════════
section('1. Natural key — the business identifier');

/** Identity IS the registration. */
final class NaturalKeyVehicle
{
    public function __construct(
        private string $registration,
        private int    $odometer,
    ) {}

    public function id(): string
    {
        return $this->registration;
    }

    public function reRegister(string $registration): void
    {
        $this->registration = $registration;
    }
}

$jobCardsByVehicle = [];

$vehicle = new NaturalKeyVehicle('AB12CDE', 84_500);
$jobCardsByVehicle[$vehicle->id()] = ['JC-1001', 'JC-1002'];

echo "  Job cards filed under: " . implode(', ', array_keys($jobCardsByVehicle)) . "\n";

// The vehicle is sold and re-registered — an ordinary event.
$vehicle->reRegister('XY98ZAB');

echo "  After re-registration, the vehicle's id is: {$vehicle->id()}\n";
echo "  Job cards found for it: "
   . implode(', ', $jobCardsByVehicle[$vehicle->id()] ?? ['(none)']) . "\n";

echo "\n  Two years of service history, orphaned by a normal business event.\n";
echo "  Every foreign key, every report, every audit trail now points at a\n";
echo "  registration nobody uses.\n\n";
echo "  THE TEST: a natural key is safe only when the business would call it a\n";
echo "  DIFFERENT THING if the key changed. Re-register a vehicle and it is\n";
echo "  the same vehicle, so registration fails the test.\n";


