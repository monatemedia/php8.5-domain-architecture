section('3. Application-generated identity');

final readonly class VehicleId
{
    private function __construct(public string $value) {}

    public static function generate(): self
    {
        // A demonstration generator, NOT a UUID. See the note below.
        return new self('VEH-' . strtoupper(bin2hex(random_bytes(6))));
    }

    public static function fromString(string $value): self
    {
        if (trim($value) === '') {
            throw new InvalidArgumentException('A vehicle id cannot be empty.');
        }
        return new self($value);
    }

    public function equals(self $other): bool
    {
        return $this->value === $other->value;
    }

    public function __toString(): string
    {
        return $this->value;
    }
}

final class GeneratedIdVehicle
{
    public function __construct(
        private readonly VehicleId $id,
        private string             $registration,
    ) {}

    public function id(): VehicleId
    {
        return $this->id;
    }

    public function reRegister(string $registration): void
    {
        $this->registration = $registration;
    }

    public function equals(self $other): bool
    {
        return $this->id->equals($other->id);
    }
}

$v = new GeneratedIdVehicle(VehicleId::generate(), 'AB12CDE');
echo "  Identity at construction: {$v->id()}\n";

$history = [(string) $v->id() => ['JC-1001', 'JC-1002']];
$v->reRegister('XY98ZAB');

echo "  After re-registration:    {$v->id()}\n";
echo "  Job cards still found:    " . implode(', ', $history[(string) $v->id()]) . "\n";

echo "\n  Identity exists from the first instant, survives every attribute\n";
echo "  change, and needs no database. Two vehicles built in two different\n";
echo "  processes cannot collide.\n";

echo "\n  THE COSTS, stated plainly:\n";
echo "    - 16 bytes instead of 4, on every row and every index\n";
echo "    - random identifiers fragment B-tree indexes badly, which is what\n";
echo "      UUID v7 (time-ordered) exists to fix — use it in real systems\n";
echo "    - the identifier means nothing to a human reading a log\n";


// ═══════════════════════════════════════════════════════════════════════════
section('A note on the generator above');

echo "  VehicleId::generate() uses random_bytes(), which is cryptographically\n";
echo "  secure and entirely sufficient for a course. It is NOT a UUID and\n";
echo "  should not be described as one.\n\n";
echo "  In production, use a UUID library — ramsey/uuid or symfony/uid — and\n";
echo "  prefer v7 over v4 so that the identifiers sort by creation time. The\n";
echo "  difference is not cosmetic: v4 identifiers arrive in random index\n";
echo "  positions, which on a large table costs real write throughput.\n\n";
echo "  This course generates its own because Modules 0 to 2 deliberately have\n";
echo "  no Composer dependencies at all.\n";


