section('2. Surrogate key — generated by the database');

final class SurrogateKeyVehicle
{
    public function __construct(
        private ?int   $id,
        private string $registration,
    ) {}

    public function id(): ?int
    {
        return $this->id;
    }

    public function assignId(int $id): void
    {
        $this->id = $id;
    }

    public function equals(self $other): bool
    {
        // What is the correct answer when neither has been saved?
        return $this->id !== null && $this->id === $other->id;
    }

    public function registration(): string
    {
        return $this->registration;
    }
}

$new = new SurrogateKeyVehicle(null, 'AB12CDE');
echo "  A brand new vehicle, not yet saved. Its id is: ";
var_dump($new->id());

echo "\n  Questions it cannot answer yet:\n\n";
echo "    - Is this the same vehicle as that one?     ";
$sameData = new SurrogateKeyVehicle(null, 'AB12CDE');
echo ($new->equals($sameData) ? 'yes' : 'no') . "   <- and it is not 'no', it is 'unknown'\n";
echo "    - Can a job card reference it?              no, there is nothing to reference\n";
echo "    - Can it be put in a set or used as a key?  no\n";

$new->assignId(4471);
echo "\n  After saving, id = " . var_export($new->id(), true) . " and all three become yes.\n";

echo "\n  The cost is not the null itself. It is that the null spreads: every\n";
echo "  constructor grows a ?int, every equals() grows a null branch, and\n";
echo "  every consumer must handle an object that does not know who it is.\n";
echo "  That is Lesson 0.2's shared-model tell — nullable fields whose\n";
echo "  population depends on where the object came from — arriving on your\n";
echo "  domain model.\n";
echo "\n  And the deeper problem: you cannot construct a complete Vehicle\n";
echo "  without a database. Rule 1 is broken in the most inconvenient place\n";
echo "  there is, because it hits every test you will ever write.\n";


